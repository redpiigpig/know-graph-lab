# -*- coding: utf-8 -*-
"""把人工挑好的預告片分鏡（用接觸表上的編號）寫成 建議配圖.json，供細流表引用。

接觸表在 素材/預告片/接觸表/，每格左下角的 [NNN] 就是這裡填的編號。
換圖只要改這張表的數字，重跑 make_cues.py 即可。
"""
import json
from pathlib import Path

PROJ = Path(r"G:\我的雲端硬碟\創作\影片創作\人魚島解說")
IDX = PROJ / "素材" / "預告片" / "截圖索引.json"
OUT = PROJ / "素材" / "預告片" / "建議配圖.json"

# 節點 → (接觸表編號, 備註)
PICK = {
    "N01": ([287, 223], "島嶼全景開場；[223] 是「原作・脚本：ナガノ」字卡，講到毫無人性時可切"),
    "N02": ([253], "「人魚の秘密」洞穴標題畫面，當作暴雷警告的底圖"),
    "N10": ([224, 385, 228, 232], "[224] 島上歡迎布條；[385] 台版字幕「真正原因是？」；[228][232] 免費美食"),
    "N11": ([253, 252, 241], "[252] 兩隻人魚跟班；[241] 賽蓮的紅色魚尾"),
    "N12": ([388, 390, 258], "[388]「島上的居民陸續遭到綁架」；[258] 洞穴裡被綑住的一排；[390]「他們都失蹤了嗎」"),
    "N13": ([247, 399, 392], "[247] 吉伊拿武器；[392]「去討伐那傢伙吧」"),
    "N14": ([260, 294, 289], "營火晚會三張，[260] 帶煙火，適合配「吉伊選擇沉默」"),
    "N20": ([287, 233], "人魚島全景，當作中央樞紐的底圖"),
    "N21": ([241, 394, 392], "[394] 魚尾把岩石打碎，力量不對等的最佳畫面"),
    "N22": ([389, 398, 396], "島民群像（需你確認哪張是村民、哪張是討伐隊）"),
    "N23": ([225, 384], "戴花圈的兩位（我判斷是一葉二葉，請你確認）"),
    "N24": ([391, 245, 251], "吉伊一行三人"),
    "N30": ([397], "「討伐？」眾人圍著，當共業結構的引子"),
    "N40": ([394, 242], "賽蓮發威；講「她其實看見傷疤」時可停在特寫"),
    "N42": ([255, 296], "夜色與月亮，配沉默的旁觀者"),
    "N73": ([260, 295], "營火收尾，接結語"),
}


def main():
    idx = {s["n"]: s for s in json.loads(IDX.read_text(encoding="utf-8"))}
    out, missing = {}, []
    for node, (nums, note) in PICK.items():
        shots = []
        for n in nums:
            s = idx.get(n)
            if not s:
                missing.append(n)
                continue
            shots.append(f"[{n:03d}] {s['file']}")
        out[node] = {"shots": shots, "note": note}
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"寫出 {len(out)} 個節點的建議配圖" + (f"；找不到編號 {missing}" if missing else ""))


if __name__ == "__main__":
    main()
