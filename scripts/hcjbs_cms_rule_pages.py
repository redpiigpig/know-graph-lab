def page_ethics():
    out = []
    for kind, val in ETHICS:
        if kind in ('intro', 'tail'):
            out.append(p(val))
        elif kind == 'note':
            out.append(p(val, indent=1))
        elif kind == 'h':
            out.append(h(val))
        else:
            name, body = val
            out.append(p(f'{name}：{body}', indent=1))
    return '\n'.join(out)


