def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--inplace", action="store_true")
    a = ap.parse_args()

    text = SRC.read_text(encoding="utf-8")
    if "[^" in text:
        sys.exit("🚨 原稿已經有註號了，先確認是不是重複跑。")

    notes = []
    for anchor, note in ANCHORS:
        n = text.count(anchor)
        if n != 1:
            sys.exit(f"🚨 錨句出現 {n} 次，無法定位：{anchor[:34]}")
        notes.append(note)
        # 國史館體例：註號置於標點符號之後
        text = text.replace(anchor, anchor + f"[^{len(notes)}]", 1)

    # 日韓段落：插在文獻回顧（一）的「缺口」段之前，並帶三條註
    cue = "**缺口**：這些研究大多以單一國別或單一宗教為單位。"
    if text.count(cue) != 1:
        sys.exit("🚨 找不到文獻回顧（一）的缺口段")
    jp = ("小川原正道，《近代日本の仏教者：アジア体験と思想の変容》"
          "（東京：慶應義塾大学出版会，2010年）；大谷栄一，"
          "《近代仏教という視座：戦争・アジア・社会主義》（東京：ぺりかん社，2012年）；"
          "島薗進，《日本仏教の社会倫理：「正法」理念から考える》"
          "（東京：岩波書店，2013年）。")
    col = ("駒込武，《植民地帝国日本の文化統合》（東京：岩波書店，1996年）；韓晳曦，"
           "《日本の朝鮮支配と宗教政策》（東京：未来社，1988年）。")
    kr = ("유동식，《한국신학의 광맥》（서울：다산글방，2003년）；강인철，"
          "《한국기독교회와 국가・시민사회: 1945~1960》"
          "（서울：한국기독교역사연구소，2003년）；김광식，《한국근대불교사연구》"
          "（서울：민족사，1996년）；오경후，《한국근대불교사론》（서울：문현，2020년）。")
    # 這三條的編號緊接在既有註之後
    base = len(notes)
    para = (JP_KR_PARA.replace("[^15]", f"[^{base + 1}]")
                      .replace("[^16]", f"[^{base + 2}]")
                      .replace("[^17]", f"[^{base + 3}]"))
    notes += [jp, col, kr]
    text = text.replace(cue, para + "\n" + cue, 1)

    # 換掉整節參考書目（到附錄之前）
    start = text.index("## 參考書目")
    end = text.index("## 附錄")
    text = text[:start] + BIBLIO.read_text(encoding="utf-8").rstrip() + "\n\n---\n\n" + text[end:]
    text = text.replace("參考書目　　23", "徵引書目　　23")

    text = text.rstrip() + "\n\n" + "\n".join(
        f"[^{i}]: {n}" for i, n in enumerate(notes, 1)) + "\n"

    out = SRC if a.inplace else SRC.with_name(SRC.stem + "_國史館體例.md")
    out.write_text(text, encoding="utf-8")
    print(f"{len(notes)} 條腳註　→ {out.name}")


if __name__ == "__main__":
    main()
