def apply(check_only=False):
    srcs = {n: io.open(HERE / n, encoding='utf-8').read() for n in DATA
            if (HERE / n).exists()}
    done, missing, dup = [], [], []

    for old, new in HOOKS.items():
        hit = [n for n, s in srcs.items() if repr(old) in s]
        if not hit:
            missing.append(old)
            continue
        if len(hit) > 1:
            dup.append((old, hit))
        n = hit[0]
        srcs[n] = srcs[n].replace(repr(old), repr(new), 1)
        done.append((n, old[:26]))

    for n, pairs in DEDUP.items():
        if n not in srcs:
            continue
        for old, new in pairs:
            if repr(old) in srcs[n]:
                srcs[n] = srcs[n].replace(repr(old), repr(new), 1)
                done.append((n, '（去重）' + old[:20]))
            else:
                missing.append('（去重）' + old)

    print(f'置換 {len(done)} 題')
    for old in missing:
        print('  ⚠ 找不到：', old[:44])
    for old, hit in dup:
        print('  ⚠ 出現在多個檔（只換第一個）：', old[:30], hit)
    if not check_only:
        for n, s in srcs.items():
            io.open(HERE / n, 'w', encoding='utf-8').write(s)
    return len(missing)


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    sys.exit(1 if apply('--check' in sys.argv) else 0)
