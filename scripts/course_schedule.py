def rendered_rows(c):
    """發給學生的樣子：(週次, 日期, [單元標題, 補充說明…])——不含章號。"""
    return [(label, date, [title] + list(extra)) for label, date, title, extra, _ in c['rows']]


def units(c):
    """備課／簡報用：(週次, 日期, 單元標題, 章號清單)，跳過考試與自主學習週。"""
    out = []
    for label, date, title, _extra, chs in c['rows']:
        if chs and not title.startswith(SELF_STUDY):
            out.append((label, date, title, chs))
    return out


