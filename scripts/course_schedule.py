def rendered_rows(c):
    """把 rows 的章號換成章名，回傳 (週次, 日期, [內容行])。"""
    out = []
    for label, date, items in c['rows']:
        lines, buf = [], ''
        for it in items:
            if isinstance(it, int):
                text = chapter_title(c['chapters'], it)
                if buf:
                    lines.append(buf + text)
                    buf = ''
                else:
                    lines.append(text)
            elif it.endswith('：'):
                buf = it
            else:
                lines.append(buf + it if buf else it)
                buf = ''
        if buf:
            lines.append(buf.rstrip('：'))
        out.append((label, date, lines))
    return out


