from course_quote_bible import bible


def q(title, lines, source, **kw):
    """一張原文頁。kw 可給 sub（副標）與 alt（並列本）。"""
    return ('quote', title, list(lines), dict(source=source, **kw))


def scripture(title, code, ch, a, b=None, **kw):
    """一張經文頁：文字與出處都從版本庫取。"""
    lines, src = bible(code, ch, a, b)
    return q(title, lines, src, **kw)


