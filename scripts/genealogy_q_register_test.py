def load(book):
    d = json.loads((MORPH / f"{book}.json").read_text(encoding="utf-8"))
    out = {}
    for k, ws in d["byVerse"].items():
        p = k.split(".")
        out[(int(p[1]), int(p[2]))] = ws
    return out


def inside(cv, ranges):
    return any((cv >= (c1, v1) and cv <= (c2, v2)) for c1, v1, c2, v2 in ranges)


def scan(book, ranges):
    doc = load(book)
    words, it, sc = 0, Counter(), Counter()
    verses = 0
    for cv in sorted(doc):
        if not inside(cv, ranges):
            continue
        verses += 1
        for w in doc[cv]:
            words += 1
            lem = (w.get("lemma") or "").strip()
            if lem in ITINERANT:
                it[lem] += 1
            if lem in SCRIBAL:
                sc[lem] += 1
    return verses, words, it, sc


