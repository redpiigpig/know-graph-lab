def splice(path, blocks):
    src = io.open(path, encoding='utf-8').read()
    for n, items in blocks.items():
        # 找出 "N: {'title': '...', 'items': [" 到對應的 "]}," 為止
        m = re.search(r"^%d: \{'title': (.*?), 'items': \[$" % n, src, re.M)
        if not m:
            sys.exit(f'找不到第 {n} 章的區塊：{path}')
        start = m.end()
        end = src.index('\n]},', start)
        body = []
        for stem, opts, ans, why in items:
            body.append('    (%r,\n     %r, %d,\n     %r),\n' % (stem, opts, ans, why))
        src = src[:start] + '\n' + ''.join(body) + src[end:]
    io.open(path, 'w', encoding='utf-8').write(src)
    print(f'✔ {Path(path).name}：已置換第 {sorted(blocks)} 章')


