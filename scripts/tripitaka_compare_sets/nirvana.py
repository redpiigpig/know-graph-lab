def _nv(k, title, intro, units, nan, bei=None, fa=None, nan_extra=None, bei_extra=None, fa_extra=None, slug=None):
    """k＝南本品號。nan＝南本切點；bei＝{義段: 北本切點} 只列與南本不同的（None＝該節北本無）；
    fa＝法顯本切點（None＝法顯本無此品）。*_extra 另加 src 欄（end、reorder…）。"""
    slug = slug or f"mahaparinirvana-c{k:02d}"
    vs = []
    if fa:
        ex = dict(fa_extra or {})
        vs.append({"id": "T0376", "lang": "lzh", "label": _NV_WHO["T0376"][0], "who": _NV_WHO["T0376"][1],
                   "src": {"work": "T0376", "nodes": _NV_FA[k], "start": fa[0][1]} | {x: y for x, y in ex.items() if x != "reorder"},
                   "cuts": fa} | ({"reorder": True} if ex.get("reorder") else {}))
    bc = []
    bei = bei or {}
    for u, s in nan:
        b = bei.get(u, s)
        if b is not None:
            bc.append((u, b))
    for u, s in bei.items():   # 北本獨有的義段
        if u not in dict(nan):
            bc.append((u, s))
    order = [u for u, _ in units]
    bc.sort(key=lambda x: order.index(x[0]))
    ex = dict(bei_extra or {})
