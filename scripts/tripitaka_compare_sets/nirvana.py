def _nv_close(last_end=None):
    """北本不分品取文：每組的 end＝下一組北本的起點；下一組落在北本新品時取到品題前。"""
    for n, (k, slug) in enumerate(_NV_ORDER):
        v = next(x for x in SETS[slug]["versions"] if x["id"] == "T0374")
        if "end" in v["src"]:
            continue
        if n + 1 >= len(_NV_ORDER):   # 最後一組：北本截到尚未建組的下一品起點
            if last_end:
                v["src"]["end"] = last_end
            continue
        k2, slug2 = _NV_ORDER[n + 1]
        nxt = next(x for x in SETS[slug2]["versions"] if x["id"] == "T0374")
        v["src"]["end"] = _NV_BEI_HEADS.get(k2) if k2 != k and k2 in _NV_BEI_HEADS else nxt["src"]["start"]


