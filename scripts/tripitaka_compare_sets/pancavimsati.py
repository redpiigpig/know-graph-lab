def _pv_whole(work, nodes, start, extra):
    """這一組恰好是該本的一整個（且只一個）目錄節點：才掛節點錨點。"""
    if len(nodes) != 1 or "end" in extra:
        return False
    # 本檔在主檔定義 zh_text 之前就被執行，這裡自己讀節點首段
    toc = json.loads((TRIP / f"{work}.toc.json").read_text(encoding="utf-8"))
    hit = [n["i"] for n in (toc if isinstance(toc, list) else toc["toc"]) if n["head"] == nodes[0]]
    head = ""
    for ln in (TRIP / f"{work}.jsonl").read_text(encoding="utf-8").splitlines():
        s = json.loads(ln) if ln.strip() else None
        if s and s["d"] in hit and s["kind"] not in ("head", "byline"):
            head += s["sources"].get("lzh", "")
            if len(head) >= len(start):
                break
    return head.startswith(start)


