// 正藏 —— 摩尼親撰
//
// 本藏收摩尼本人所撰的正典書目：七部大經＋《沙卜爾干》＋《圖經》。
//
// 🚨 **這一藏幾乎整個是空的，而且必須讓它看起來是空的。**
//    七部大經沒有一部傳世。本藏每一卷的「原文」欄能填的，是別的語言的殘葉、
//    敵手駁論裡的引文、或者只是一個書名。版面上必須把這件事說白——
//    一個看起來收得滿滿的摩尼教正藏是假的。
//
// ══════════ 七經的書目從哪裡來（三方互證，所以可靠）══════════
//
//   ① 阿爾—納迪姆《群書類述》(al-Fihrist, 987)：阿拉伯文，逐部列名並記章數
//   ② 科普特文《凱法萊亞》與《講道集》：摩尼教徒自己的列舉
//   ③ 敦煌《摩尼光佛教法儀略》(731)：漢文音譯名＋意譯名，拂多誕奉唐玄宗詔所撰
//
//   三份書單來自三個互不相通的傳統（巴格達、埃及、長安），列的是同一批書。
//   所以「摩尼定過一份正典」這件事，比絕大多數古代宗教的正典形成都更有把握。
//
// ══════════ 漢名比定：五部穩，兩部有爭議 ══════════
//
//   音譯對得上原文的（穩）：
//     阿羅瓚部  ← Rāzān（敘利亞語「祕密」）      → 祕密之書
//     俱緩部    ← Kawān（敘利亞語「巨人」）      → 巨人書
//     阿拂胤部  ← āfrīn（中古波斯語「讚祝」）    → 詩篇與祈禱
//     尋提賀部  ← Sīmat ḥayyē（敘利亞語「生命的寶藏」）→ 生命寶庫
//     大應輪部  ← 意譯「徹盡萬法根源智經」，各家一致比定為《活福音》
//
//   🚨 有爭議的兩部：**泥萬部**（律藏經／藥藏經）與**鉢迦摩帝夜部**（證明過去教經）
//     對應《論集》(Pragmateia) 與《書信集》，但哪一部對哪一部，各家不一致。
//     「鉢迦摩帝夜」音近 Pragmateia 是最直接的理由，但「泥萬」的原文迄無定說。
//     本站兩條都標 disputed，**不替學界下判斷**。誰要引用請自己看原文。

